import 'package:flutter/material.dart';

class PhoneStockItem {
  final String id;
  final String name;
  final String brand;
  final String storage;
  final String color;
  final int batteryHealth;
  final String conditionGrade;
  final String gradeDescription;
  final int refurbishedPrice;
  final int originalPrice;
  final int stockQuantity;
  final IconData icon;
  final List<String> highlights;
  final String? imageUrl;
  final List<String>? galleryUrls;
  final bool isLiveHeldOnBench;

  final String? sku;
  final String? imei;
  final String? storeId;
  final String hsnCode;
  final double taxPercent;

  const PhoneStockItem({
    required this.id,
    required this.name,
    required this.brand,
    required this.storage,
    required this.color,
    required this.batteryHealth,
    required this.conditionGrade,
    required this.gradeDescription,
    required this.refurbishedPrice,
    required this.originalPrice,
    required this.stockQuantity,
    required this.icon,
    required this.highlights,
    this.imageUrl,
    this.galleryUrls,
    this.isLiveHeldOnBench = false,
    this.sku,
    this.imei,
    this.storeId,
    this.hsnCode = '85171200',
    this.taxPercent = 18.0,
  });

  int get savingsAmount => originalPrice - refurbishedPrice;
  int get savingsPercent => originalPrice > 0 ? (((originalPrice - refurbishedPrice) / originalPrice) * 100).round() : 0;
  bool get isAvailable => stockQuantity > 0;
  String get effectiveSku => sku ?? id;

  Map<String, dynamic> toJson() => {
    'id': id,
    'sku': sku ?? id,
    'imei': imei,
    'storeId': storeId,
    'hsnCode': hsnCode,
    'taxPercent': taxPercent,
    'name': name,
    'brand': brand,
    'storage': storage,
    'color': color,
    'batteryHealth': batteryHealth,
    'conditionGrade': conditionGrade,
    'gradeDescription': gradeDescription,
    'refurbishedPrice': refurbishedPrice,
    'originalPrice': originalPrice,
    'stockQuantity': stockQuantity,
    'iconCodePoint': icon.codePoint,
    'highlights': highlights,
    'imageUrl': imageUrl,
    'galleryUrls': galleryUrls,
    'isLiveHeldOnBench': isLiveHeldOnBench,
  };

  factory PhoneStockItem.fromJson(Map<String, dynamic> json) => PhoneStockItem(
    id: (json['id'] ?? json['product_id'] ?? json['sku']) as String? ?? '',
    sku: (json['sku'] ?? json['id']) as String?,
    imei: (json['imei'] ?? json['serial_number'] ?? json['serialNumber']) as String?,
    storeId: (json['storeId'] ?? json['store_id']) as String?,
    hsnCode: (json['hsnCode'] ?? json['hsn_code'] ?? '85171200') as String,
    taxPercent: (json['taxPercent'] ?? json['tax_percent'] as num?)?.toDouble() ?? 18.0,
    name: (json['name'] ?? json['title'] ?? json['product_name']) as String? ?? '',
    brand: (json['brand'] ?? json['manufacturer']) as String? ?? 'Apple',
    storage: (json['storage'] ?? json['capacity']) as String? ?? '128 GB',
    color: json['color'] as String? ?? 'Midnight',
    batteryHealth: (json['batteryHealth'] ?? json['battery_health'] as num?)?.toInt() ?? 90,
    conditionGrade: (json['conditionGrade'] ?? json['condition_grade'] ?? json['grade']) as String? ?? 'Superb (Pristine)',
    gradeDescription: (json['gradeDescription'] ?? json['grade_description']) as String? ?? '100% verified pristine display & battery.',
    refurbishedPrice: (json['refurbishedPrice'] ?? json['refurbished_price'] ?? json['price'] ?? json['selling_price'] as num?)?.toInt() ?? 0,
    originalPrice: (json['originalPrice'] ?? json['original_price'] ?? json['mrp'] as num?)?.toInt() ?? 0,
    stockQuantity: (json['stockQuantity'] ?? json['stock_quantity'] ?? json['quantity'] ?? json['qty'] as num?)?.toInt() ?? 0,
    icon: json['iconCodePoint'] != null
        ? IconData(json['iconCodePoint'] as int, fontFamily: 'MaterialIcons')
        : ((json['brand'] ?? json['manufacturer']) == 'Apple' ? Icons.phone_iphone_rounded : Icons.smartphone_rounded),
    highlights: (json['highlights'] as List<dynamic>?)?.map((e) => e.toString()).toList() ?? [],
    imageUrl: ((json['imageUrl'] ?? json['image_url'] ?? json['image']) as String?)?.replaceAll('.jpg', '.png'),
    galleryUrls: (json['galleryUrls'] ?? json['gallery_urls'] as List<dynamic>?)?.map((e) => e.toString().replaceAll('.jpg', '.png')).toList(),
    isLiveHeldOnBench: (json['isLiveHeldOnBench'] ?? json['is_live_held_on_bench'] ?? json['is_held']) as bool? ?? false,
  );

  PhoneStockItem copyWith({
    String? id,
    String? name,
    String? brand,
    String? storage,
    String? color,
    int? batteryHealth,
    String? conditionGrade,
    String? gradeDescription,
    int? refurbishedPrice,
    int? originalPrice,
    int? stockQuantity,
    IconData? icon,
    List<String>? highlights,
    String? imageUrl,
    List<String>? galleryUrls,
    bool? isLiveHeldOnBench,
    String? sku,
    String? imei,
    String? storeId,
    String? hsnCode,
    double? taxPercent,
  }) => PhoneStockItem(
    id: id ?? this.id,
    name: name ?? this.name,
    brand: brand ?? this.brand,
    storage: storage ?? this.storage,
    color: color ?? this.color,
    batteryHealth: batteryHealth ?? this.batteryHealth,
    conditionGrade: conditionGrade ?? this.conditionGrade,
    gradeDescription: gradeDescription ?? this.gradeDescription,
    refurbishedPrice: refurbishedPrice ?? this.refurbishedPrice,
    originalPrice: originalPrice ?? this.originalPrice,
    stockQuantity: stockQuantity ?? this.stockQuantity,
    icon: icon ?? this.icon,
    highlights: highlights ?? this.highlights,
    imageUrl: imageUrl ?? this.imageUrl,
    galleryUrls: galleryUrls ?? this.galleryUrls,
    isLiveHeldOnBench: isLiveHeldOnBench ?? this.isLiveHeldOnBench,
    sku: sku ?? this.sku,
    imei: imei ?? this.imei,
    storeId: storeId ?? this.storeId,
    hsnCode: hsnCode ?? this.hsnCode,
    taxPercent: taxPercent ?? this.taxPercent,
  );

